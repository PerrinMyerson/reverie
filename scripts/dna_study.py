#!/usr/bin/env python3
"""DNA as reversible memory: a storage codec and molecular event recorders.

1. **Codec** (`reverie.dna.encode` / `decode`): a Goldman-style rotating code
   written once as a Reverie encoder; the decoder is the same program run
   backward. Measures round-trip exactness on random payloads, density, GC
   content, and what happens to single-base substitution errors: detected
   (the decoder's no-homopolymer assertion fails) or silently decoded to
   different bytes.
2. **Recorders** (`reverie.dna.RECORDERS`): exact, exhaustive H(history |
   DNA) for recorder architectures, over every history of n events drawn
   from k signals. That is the number of bits of a cell's history its DNA
   cannot give back, i.e. the witness a decoder would need.

    python3 scripts/dna_study.py --markdown-output docs/research/dna.md
"""

from __future__ import annotations

import argparse
import json
import os
import random
import sys
from pathlib import Path
from typing import Any, Dict, List


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--payloads", type=int, default=200)
    parser.add_argument("--payload-bytes", type=int, default=64)
    parser.add_argument("--mutations", type=int, default=3000)
    parser.add_argument("--max-events", type=int, default=8)
    parser.add_argument("--signals", default="2,3,4")
    parser.add_argument("--seed", type=int, default=9)
    parser.add_argument("--json-output", type=Path)
    parser.add_argument("--markdown-output", type=Path)
    parser.add_argument("--self-test", action="store_true")
    return parser.parse_args()


def codec_study(args) -> Dict[str, Any]:
    from reverie import dna

    rng = random.Random(args.seed)
    exact = 0
    gc = []
    homopolymer_free = True
    strands: List[tuple] = []
    for _ in range(args.payloads):
        payload = bytes(rng.randrange(256) for _ in range(args.payload_bytes))
        strand = dna.encode(payload)
        exact += dna.decode(strand) == payload
        homopolymer_free &= all(a != b for a, b in zip(strand, strand[1:]))
        gc.append(sum(b in "GC" for b in strand[1:]) / (len(strand) - 1))
        strands.append((payload, strand))

    detected = silent = 0
    for _ in range(args.mutations):
        payload, strand = rng.choice(strands)
        i = rng.randrange(1, len(strand))
        base = rng.choice([b for b in dna.BASES if b != strand[i]])
        mutated = strand[:i] + base + strand[i + 1 :]
        try:
            decoded = dna.decode(mutated)
        except Exception:
            detected += 1
            continue
        silent += decoded != payload
    return {
        "payloads": args.payloads,
        "payload_bytes": args.payload_bytes,
        "round_trip_exact": exact,
        "homopolymer_free": homopolymer_free,
        "bits_per_nucleotide": 8 / dna.TRITS_PER_BYTE,
        "gc_mean": sum(gc) / len(gc),
        "gc_min": min(gc),
        "gc_max": max(gc),
        "substitutions": args.mutations,
        "substitutions_detected": detected,
        "substitutions_silent": silent,
    }


def recorder_study(args) -> Dict[str, Any]:
    from reverie import dna

    rows = []
    for k in [int(x) for x in args.signals.split(",")]:
        for n in range(1, args.max_events + 1):
            row = {"signals": k, "events": n}
            for name, recorder in dna.RECORDERS.items():
                states = dna.recorder_states(recorder, n, k)
                h, forget = dna.history_entropy(states)
                row["history_bits"] = h
                row[name] = {"states": len(states), "forgotten_bits": forget}
            rows.append(row)
    return {"recorders": list(dna.RECORDERS), "rows": rows}


def markdown(result: Dict[str, Any]) -> str:
    c, r = result["codec"], result["recorders"]
    lines = [
        "# DNA as reversible memory",
        "",
        "Generated by `scripts/dna_study.py`.",
        "",
        "## A storage codec whose decoder is generated",
        "",
        "A Goldman-style rotating code (each base-3 digit picks one of the three bases that differ "
        "from the previous base, so no homopolymers), written once as a Reverie encoder "
        "(`reverie.dna.codec_source`). The decoder is the same program run backward.",
        "",
        f"- Round trip: **{c['round_trip_exact']} / {c['payloads']}** random {c['payload_bytes']}-byte "
        f"payloads decoded exactly; every strand homopolymer-free: **{c['homopolymer_free']}**.",
        f"- Density {c['bits_per_nucleotide']:.2f} bits/nt (6 trits per byte; the rotating code's "
        f"ceiling is log2 3 = 1.58). GC content {c['gc_mean']:.1%} on average "
        f"({c['gc_min']:.1%}–{c['gc_max']:.1%}); the code does not constrain GC.",
        f"- Single-base substitutions: {c['substitutions_detected']:,} of {c['substitutions']:,} "
        f"(**{c['substitutions_detected'] / c['substitutions']:.0%}**) are rejected by the generated "
        "decoder because they create a homopolymer (its no-homopolymer assertion runs backward too); "
        f"{c['substitutions_silent']:,} ({c['substitutions_silent'] / c['substitutions']:.0%}) decode to "
        "different bytes without complaint, so real systems still need error-correcting codes on top.",
        "",
        "## How much of a cell's history can its DNA give back?",
        "",
        "Every history of n events drawn from k signals is enumerated, so these are exact numbers. "
        "The table gives the bits of history the recorder's DNA state *cannot* give back, "
        "H(history | DNA), out of n·log2 k. That is the witness a decoder would need.",
        "",
    ]
    names = r["recorders"]
    for k in sorted({row["signals"] for row in r["rows"]}):
        lines += [
            f"### {k} signals",
            "",
            "| events | history bits | " + " | ".join(names) + " |",
            "|---:|---:|" + "---:|" * len(names),
        ]
        for row in r["rows"]:
            if row["signals"] != k:
                continue
            cells = " | ".join(f"{row[name]['forgotten_bits']:.2f}" for name in names)
            lines.append(f"| {row['events']} | {row['history_bits']:.2f} | {cells} |")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    args = parse_args()
    if args.self_test:
        args.payloads, args.payload_bytes, args.mutations, args.max_events = 10, 8, 200, 4
    result = {
        "schema": "reverie_dna_v1",
        "codec": codec_study(args),
        "recorders": recorder_study(args),
    }
    if args.self_test:
        c = result["codec"]
        assert c["round_trip_exact"] == c["payloads"] and c["homopolymer_free"], c
        for row in result["recorders"]["rows"]:
            assert row["ordered tape (CRISPR array, DNA Typewriter)"]["forgotten_bits"] == 0, row
            flips = row["site flips (integrase switches)"]["forgotten_bits"]
            assert all(row[name]["forgotten_bits"] <= flips + 1e-9 for name in result["recorders"]["recorders"]), row
        print("ok: dna self-test passed")
        return 0
    text = markdown(result)
    if args.json_output:
        args.json_output.write_text(json.dumps(result, indent=2) + "\n")
    if args.markdown_output:
        args.markdown_output.parent.mkdir(parents=True, exist_ok=True)
        args.markdown_output.write_text(text)
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
