#!/usr/bin/env python3
"""Rollback netcode: rewinding by reverse execution vs. snapshots.

Uses `reverie.rollback`: a two-player fighting game, plus N bouncing
projectiles as scalable scenery, written as a reversible Reverie frame step.
For each N it:

1. plays a match with the remote player's input delayed, rolling back on
   every misprediction, once restoring snapshots and once running backward,
   and checks both end bit-identical to a ground-truth run that knew every
   input in advance;
2. measures what each strategy must keep per frame of rollback window, in
   raw values and in coded bits (zig-zag + Elias-gamma, so zeros cost 1 bit);
3. measures the engine cost of one frame forward and one frame backward
   (long batched runs, so Python conversion is amortised), and from that the
   cost of a rollback of depth k: snapshots replay k frames, reverse
   execution reverses k and replays k.

    python3 scripts/rollback_netcode_benchmark.py --markdown-output docs/research/rollback-netcode.md
"""

from __future__ import annotations

import argparse
import json
import platform
import statistics
import sys
import time
from pathlib import Path
from typing import Any, Dict, List


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--projectiles", default="0,16,64,256")
    parser.add_argument("--match-frames", type=int, default=180)
    parser.add_argument("--timing-frames", type=int, default=600)
    parser.add_argument("--delay", type=int, default=6)
    parser.add_argument("--seed", type=int, default=5)
    parser.add_argument("--json-output", type=Path)
    parser.add_argument("--markdown-output", type=Path)
    parser.add_argument("--self-test", action="store_true")
    return parser.parse_args()


def median_time(fn, repeats: int = 5) -> float:
    samples = []
    for _ in range(repeats):
        started = time.perf_counter()
        fn()
        samples.append(time.perf_counter() - started)
    return statistics.median(samples)


def measure(n: int, args: argparse.Namespace) -> Dict[str, Any]:
    from reverie import rollback as rb
    from reverie.ledger import code_length_bits, flatten

    match = rb.Match(n_projectiles=n, frames=args.match_frames, seed=args.seed)
    truth = match.ground_truth()
    results = {}
    for mode in ("snapshot", "reverse"):
        session = rb.Rollback(match, delay=args.delay, mode=mode)
        out = session.play()
        results[mode] = {
            "state_matches_truth": all(out[k] == truth[k] for k in rb.STATE),
            "witness_matches_truth": all(out[k] == truth[k] for k in rb.WITNESS)
            if mode == "reverse"
            else None,
            "rollbacks": session.stats.rollbacks,
            "frames_resimulated": session.stats.frames_resimulated,
            "frames_reversed": session.stats.frames_reversed,
            "max_depth": session.stats.max_depth,
        }

    frames = args.match_frames
    state_values = sum(1 for _ in flatten({k: truth[k] for k in rb.STATE}))
    state_bits = sum(code_length_bits(v) for v in flatten({k: truth[k] for k in rb.STATE}))
    witness_values = sum(1 for _ in flatten({k: truth[k] for k in rb.WITNESS})) / frames
    witness_bits = sum(code_length_bits(v) for v in flatten({k: truth[k] for k in rb.WITNESS})) / frames
    events = sum(1 for v in flatten({k: truth[k] for k in rb.WITNESS}) if v) / frames

    # Engine cost per frame, batched.
    timing = rb.Match(n_projectiles=n, frames=args.timing_frames, seed=args.seed)
    seeds = timing.store(timing.state0, timing.move, timing.attack, 0, timing.frames - 1)
    final = timing.program.run(seeds)
    forward = median_time(lambda: timing.program.run(seeds)) / timing.frames
    backward = median_time(lambda: timing.program.reverse(final)) / timing.frames
    restored = timing.program.reverse(final)

    return {
        "projectiles": n,
        "correctness": results,
        "reverse_restores_initial_state": all(restored[k] == timing.state0[k] for k in rb.STATE),
        "per_frame": {
            "snapshot_values": state_values,
            "snapshot_coded_bits": state_bits,
            "witness_values": witness_values,
            "witness_coded_bits": witness_bits,
            "witness_nonzero_entries": events,
        },
        "engine_us_per_frame": {"forward": forward * 1e6, "backward": backward * 1e6},
    }


def markdown(rows: List[Dict[str, Any]], args, host) -> str:
    d = args.delay
    lines = [
        "# Rollback netcode: reverse execution vs snapshots",
        "",
        f"Generated by `scripts/rollback_netcode_benchmark.py` ({host}). Game: two fighters "
        "(position, velocity, health, cooldown) plus N bouncing projectiles, as a reversible "
        f"Reverie frame step (`reverie.rollback`). The remote player's input arrives {d} frames "
        "late; the local client predicts \"same as last input\" and rolls back on every "
        "misprediction.",
        "",
        "## Correctness",
        "",
        "| projectiles | rollbacks | frames re-simulated | snapshot result = ground truth | reverse result = ground truth | reverse witness = ground truth |",
        "|---:|---:|---:|:---:|:---:|:---:|",
    ]
    for r in rows:
        s, v = r["correctness"]["snapshot"], r["correctness"]["reverse"]
        lines.append(
            f"| {r['projectiles']} | {s['rollbacks']} | {s['frames_resimulated']} | "
            f"{'yes' if s['state_matches_truth'] else 'NO'} | {'yes' if v['state_matches_truth'] else 'NO'} | "
            f"{'yes' if v['witness_matches_truth'] else 'NO'} |"
        )
    lines += [
        "",
        f"## Memory for a {d}-frame rollback window",
        "",
        "| projectiles | snapshot: values / frame | snapshot: coded bits / frame | witness: values / frame | witness: coded bits / frame | non-zero witness entries / frame | snapshot ÷ witness (coded) |",
        "|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for r in rows:
        p = r["per_frame"]
        lines.append(
            f"| {r['projectiles']} | {p['snapshot_values']:,} | {p['snapshot_coded_bits']:,} | "
            f"{p['witness_values']:,.0f} | {p['witness_coded_bits']:,.0f} | {p['witness_nonzero_entries']:.1f} | "
            f"{p['snapshot_coded_bits'] / p['witness_coded_bits']:.1f}x |"
        )
    lines += [
        "",
        "## Compute",
        "",
        "| projectiles | forward (us / frame) | backward (us / frame) | rollback of depth k, snapshots | rollback of depth k, reverse |",
        "|---:|---:|---:|---:|---:|",
    ]
    for r in rows:
        e = r["engine_us_per_frame"]
        lines.append(
            f"| {r['projectiles']} | {e['forward']:.1f} | {e['backward']:.1f} | "
            f"k x {e['forward']:.1f} us (+ restore copy) | k x {e['forward'] + e['backward']:.1f} us |"
        )
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    args = parse_args()
    if args.self_test:
        args.projectiles, args.match_frames, args.timing_frames = "0,3", 60, 60
    counts = [int(x) for x in args.projectiles.split(",")]
    rows = [measure(n, args) for n in counts]
    host = f"{platform.platform()}, Python {platform.python_version()}"
    if args.self_test:
        for r in rows:
            assert r["correctness"]["snapshot"]["state_matches_truth"], r
            assert r["correctness"]["reverse"]["state_matches_truth"], r
            assert r["correctness"]["reverse"]["witness_matches_truth"], r
            assert r["reverse_restores_initial_state"], r
        print("ok: rollback netcode self-test passed")
        return 0
    text = markdown(rows, args, host)
    if args.json_output:
        args.json_output.write_text(json.dumps({"host": host, "rows": rows}, indent=2) + "\n")
    if args.markdown_output:
        args.markdown_output.parent.mkdir(parents=True, exist_ok=True)
        args.markdown_output.write_text(text)
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
