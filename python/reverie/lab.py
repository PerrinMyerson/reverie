#: 1.0 in Q31 fixed point.
Q31_ONE = 1 << 31


def to_q31(value: float) -> int:
    """Round a float to Q31 fixed point."""
    return int(round(value * Q31_ONE))


def mlp_sgd_source(
    *,
    n_samples: int,
    n_features: int,
    hidden: int,
    classes: int,
    steps: int,
) -> str:
    """Reverie source for minimal-witness SGD on a ``n_features -> hidden ->
    classes`` ReLU MLP.

    Seeds: ``images`` (``n_samples x n_features`` Q31), ``labels``,
    ``order`` (sample index for each step), ``active`` (1 to train on a step,
    0 to skip it), ``start``/``stop`` (inclusive step range), ``lr`` (Q31), and
    the weights ``w1``, ``b1``, ``w2``, ``b2``.
    """
    n, d, h, c, t = n_samples, n_features, hidden, classes, steps
    return f"""\
// Minimal-witness SGD for a {d} -> {h} -> {c} ReLU MLP ({n} samples, {t} steps).
// Generated by reverie.lab.mlp_sgd_source. The witness is only the
// back-propagated errors: err_tape (output layer) and delta_tape (hidden
// layer). Activations are recomputed when running backward.

global images: tensor<int, {n}, {d}>;
global labels: tensor<int, {n}>;
global order: tensor<int, {t}>;
global active: tensor<int, {t}>;
global start = 0;
global stop = 0;
global lr = 0;

global w1: tensor<int, {d}, {h}>;
global b1: tensor<int, {h}>;
global w2: tensor<int, {h}, {c}>;
global b2: tensor<int, {c}>;

global err_tape: witness<tensor<int, {t}, {c}>>;
global delta_tape: witness<tensor<int, {t}, {h}>>;

global pre: tensor<int, {h}>;
global mask: tensor<int, {h}>;
global act: tensor<int, {h}>;
global logits: tensor<int, {c}>;
global back: tensor<int, {h}>;

procedure main() {{
  iterate int s = start to stop
    if active[s] == 1 then
      pre += vecmat_q31(images[order[s]], w1);
      pre += b1;
      mask += relu_mask_q31(pre);
      act += relu(pre);
      logits += vecmat_q31(act, w2);
      logits += b2;
      err_tape[s] += logits;
      err_tape[s] -= one_hot_q31(labels[order[s]], {c});
      back += matvec_q31(w2, err_tape[s]);
      delta_tape[s] += hadamard_q31(back, mask);
      back -= matvec_q31(w2, err_tape[s]);
      logits -= err_tape[s];
      logits -= one_hot_q31(labels[order[s]], {c});
      w2 -= scale_q31(outer_q31(act, err_tape[s]), lr);
      b2 -= scale_q31(err_tape[s], lr);
      act -= relu(pre);
      mask -= relu_mask_q31(pre);
      pre -= b1;
      pre -= vecmat_q31(images[order[s]], w1);
      w1 -= scale_q31(outer_q31(images[order[s]], delta_tape[s]), lr);
      b1 -= scale_q31(delta_tape[s], lr)
    else
      skip
    fi active[s] == 1
  end
}}
"""


def mlp_erasure_source(*, n_samples: int, n_features: int, hidden: int, classes: int) -> str:
    """Reverie source for MLP inference whose only witness is what each ReLU
    destroys: ``neg_tape[s][j] = min(pre_j, 0)``. ``act_tape`` holds the
    activations, ``logits_tape`` the logits; the inputs are kept.

    ``(act, neg)`` determines the pre-activation exactly (``pre = act + neg``),
    so ``neg`` is precisely the information the ReLU layer discards.
    """
    n, d, h, c = n_samples, n_features, hidden, classes
    return f"""\
// MLP inference with a minimal ReLU witness. Generated by
// reverie.lab.mlp_erasure_source.

global images: tensor<int, {n}, {d}>;
global w1: tensor<int, {d}, {h}>;
global b1: tensor<int, {h}>;
global w2: tensor<int, {h}, {c}>;
global b2: tensor<int, {c}>;
global act_tape: tensor<int, {n}, {h}>;
global neg_tape: witness<tensor<int, {n}, {h}>>;
global logits_tape: tensor<int, {n}, {c}>;

procedure main() {{
  iterate int s = 0 to {n - 1}
    act_tape[s] += vecmat_q31(images[s], w1);
    act_tape[s] += b1;
    neg_tape[s] += act_tape[s];
    neg_tape[s] -= relu(act_tape[s]);
    act_tape[s] -= neg_tape[s];
    logits_tape[s] += vecmat_q31(act_tape[s], w2);
    logits_tape[s] += b2
  end
}}
"""


def erasure_profile(
    weights: Dict[str, Any], images: Sequence[Sequence[int]], *, engine: str = "slot"
) -> Dict[str, Any]:
    """Run :func:`mlp_erasure_source` and summarise what each hidden neuron
    discards: how often its ReLU fires, and the coded bits of its witness."""
    from .ledger import code_length_bits

    hidden = len(weights["b1"])
    classes = len(weights["b2"])
    program = loads(
        mlp_erasure_source(
            n_samples=len(images),
            n_features=len(images[0]),
            hidden=hidden,
            classes=classes,
        ),
        engine=engine,
    )
    store = {"images": [list(row) for row in images], **weights}
    final = program.run(store)
    restored = program.reverse(final)
    neg = final["neg_tape"]
    act = final["act_tape"]
    neurons = []
    for j in range(hidden):
        column = [row[j] for row in neg]
        neurons.append(
            {
                "neuron": j,
                "erased_fraction": sum(1 for v in column if v != 0) / len(column),
                "coded_bits": sum(code_length_bits(v) for v in column),
            }
        )
    logits_bits = sum(code_length_bits(v) for row in final["logits_tape"] for v in row)
    return {
        "samples": len(images),
        "exact_reconstruction": all(
            restored[name] == value for name, value in store.items()
        ),
        "relu_witness_bits": sum(n["coded_bits"] for n in neurons),
        "activation_bits": sum(code_length_bits(v) for row in act for v in row),
        "readout_logit_bits": logits_bits,
        "neurons": neurons,
        "dead_neurons": [n["neuron"] for n in neurons if n["erased_fraction"] == 1.0],
        "linear_neurons": [n["neuron"] for n in neurons if n["erased_fraction"] == 0.0],
    }


class SearchWitness:
    """Minimal witnesses for a non-injective function on a finite domain.

    An op-by-op reversible program keeps everything each operation erases;
    the witness for ``f`` can be far larger than the information ``f``
    actually destroys about its input. The information-theoretic minimum is
    ``H(X | f(X))``. For a uniform input it is reached, to within one bit, by
    storing only the input's *index within its preimage* ``f^-1(f(x))``.
    Uncomputing then means searching the domain for the inputs with the same
    output, in a fixed order.

    This prototypes that "uncompute by search" for any deterministic ``f``
    (for example a Reverie program's ``run``). Encoding costs one evaluation of
    ``f``; decoding costs one evaluation per domain element, the price of the
    smaller witness.
    """

    def __init__(self, f, domain) -> None:
        self.f = f
        self.domain = list(domain)
        self._outputs: Optional[list] = None

    def _preimage(self, output) -> list:
        # One pass of `f` over the domain, cached: later searches are free.
        if self._outputs is None:
            self._outputs = [self.f(x) for x in self.domain]
        return [x for x, y in zip(self.domain, self._outputs) if y == output]

    def encode(self, x):
        """Return ``(f(x), index, class_size)``. ``index`` needs
        ``ceil(log2(class_size))`` bits."""
        output = self.f(x)
        preimage = self._preimage(output)
        return output, preimage.index(x), len(preimage)

    def decode(self, output, index):
        """Recover the input from the output and its index witness."""
        return self._preimage(output)[index]

    @staticmethod
    def bits(class_size: int) -> int:
        return max(0, (class_size - 1).bit_length())


WEIGHTS = ("w1", "b1", "w2", "b2")
WITNESS = ("err_tape", "delta_tape")


@dataclass
class TrainingWitness:
    """What a training run must keep to be rewound exactly."""

    steps: int
    witness_values: int
    parameter_values: int

    @property
    def per_step(self) -> float:
        return self.witness_values / max(self.steps, 1)


class SGDRewind:
    """Train, rewind and exactly unlearn with :func:`mlp_sgd_source`.

    ``data`` holds the seeds the program needs except the weights and step
    range: ``images``, ``labels``, ``order``, ``lr``.
    """

    def __init__(
        self,
        *,
        images: Sequence[Sequence[int]],
        labels: Sequence[int],
        order: Sequence[int],
        hidden: int,
        classes: int,
        lr: int,
        engine: str = "slot",
    ) -> None:
        self.n_samples = len(images)
        self.n_features = len(images[0])
        self.hidden = hidden
        self.classes = classes
        self.steps = len(order)
        self.source = mlp_sgd_source(
            n_samples=self.n_samples,
            n_features=self.n_features,
            hidden=hidden,
            classes=classes,
            steps=self.steps,
        )
        self.program: Program = loads(self.source, engine=engine)
        self.data: Dict[str, Any] = {
            "images": [list(row) for row in images],
            "labels": list(labels),
            "order": list(order),
            "lr": lr,
        }

    # -- running -------------------------------------------------------------

    def train(
        self,
        weights: Dict[str, Any],
        *,
        active: Optional[Sequence[int]] = None,
        start: int = 0,
        stop: Optional[int] = None,
        witness: Optional[Dict[str, Any]] = None,
    ) -> Dict[str, Any]:
        """Run steps ``start..stop`` forward and return the full final store
        (weights, witness tapes and data)."""
        store = dict(self.data)
        store.update(weights)
        store["active"] = list(active) if active is not None else [1] * self.steps
        store["start"] = start
        store["stop"] = self.steps - 1 if stop is None else stop
        if witness is not None:
            store.update(witness)
        return self.program.run(store)

    def rewind(self, final: Dict[str, Any], to_step: int) -> Dict[str, Any]:
        """Run steps ``to_step..stop`` backward from a final store: returns the
        store as it was before step ``to_step`` (witness slots for the rewound
        steps come back as zeros)."""
        store = dict(final)
        store["start"] = to_step
        return self.program.reverse(store)

    def unlearn(
        self, final: Dict[str, Any], sample: int
    ) -> Dict[str, Any]:
        """Exactly remove ``sample`` from a finished run: rewind to its first
        use, deactivate every step that used it, and replay the rest."""
        first = self.first_use(sample)
        if first is None:
            return final
        rewound = self.rewind(final, first)
        active = [
            0 if self.data["order"][step] == sample else flag
            for step, flag in enumerate(final["active"])
        ]
        weights = {name: rewound[name] for name in WEIGHTS}
        witness = {name: rewound[name] for name in WITNESS}
        return self.train(weights, active=active, start=first, witness=witness)

    def first_use(self, sample: int) -> Optional[int]:
        for step, index in enumerate(self.data["order"]):
            if index == sample:
                return step
        return None

    # -- accounting ----------------------------------------------------------

    def witness_size(self) -> TrainingWitness:
        params = (
            self.n_features * self.hidden + self.hidden + self.hidden * self.classes + self.classes
        )
        return TrainingWitness(
            steps=self.steps,
            witness_values=self.steps * (self.hidden + self.classes),
            parameter_values=params,
        )

    @staticmethod
    def weights(store: Dict[str, Any]) -> Dict[str, Any]:
        return {name: store[name] for name in WEIGHTS}

    @staticmethod
    def witness(store: Dict[str, Any]) -> Dict[str, List[List[int]]]:
        return {name: store[name] for name in WITNESS}
