"""Exact, checkpoint-free rewinding of SGD training, written in Reverie.

The key observation: with batch size one, every dense-layer update is a
rank-one outer product ``W -= lr * outer(input_side, output_side)``. To undo a
step exactly you only need the *output-side* factors (the back-propagated
errors), because the input-side factors (the sample and the hidden
activations) can be recomputed once the earlier layers have been restored. So
the reverse sweep restores layer 1 first, recomputes the hidden activations
from it, then restores layer 2.

:func:`mlp_sgd_source` generates a Reverie program that trains a one-hidden-
layer ReLU MLP with Q31 fixed-point SGD and keeps exactly that witness:

* ``err_tape[step]``: the output error (``classes`` integers per step);
* ``delta_tape[step]``: the hidden-layer delta (``hidden`` integers per step).

Every other intermediate value (pre-activations, ReLU mask, activations,
logits, back-propagated signal) is uncomputed inside the step. Reverie's
checker proves the program reversible, so running it backward from the final
weights and the witness restores the weights at any earlier step bit for bit,
with no stored checkpoints. :class:`SGDRewind` uses that to unlearn a training
sample exactly: rewind to the step before the sample was first used, then
replay the rest of the schedule without it. The result is bit-identical to
retraining from scratch without the sample.
"""

