"""DNA as reversible memory: a storage codec and molecular event recorders.

**Storage codec.** DNA data storage maps bytes to nucleotides under
synthesis constraints. Goldman et al. (2013) avoided homopolymers (runs of
one base) with a *rotating* code: each base-3 digit picks one of the three
bases that differ from the previous base. :func:`codec_source` writes that
encoder as a Reverie program: bytes → 6 trits → bases. The checker proves it
loses nothing, so the decoder is the same program run backward, and the
no-homopolymer rule is an assertion checked in both directions.

**Event recorders.** Molecular recorders write a cell's history into DNA:
CRISPR arrays and sequential editors append to a tape (Retro-Cascorder, DNA
Typewriter), while integrase recorders flip a fixed set of sites. Whether the
history can be read back is a reversibility question: the write must be
injective from histories to DNA states. :func:`recorder_states` models
recorder architectures exactly, and :func:`tape_recorder_source` /
:func:`flip_recorder_source` express two of them in Reverie. The tape
recorder moves the history into DNA with no witness; for the flip recorder
the checker refuses to discard the history, because the DNA alone does not
determine it.
"""

from __future__ import annotations

import itertools
import math
from collections import Counter
from typing import Callable, Dict, Iterable, List, Sequence, Tuple

from ._reverie import Program, loads

__all__ = [
    "BASES",
    "codec_source",
    "encode",
    "decode",
    "tape_recorder_source",
    "flip_recorder_source",
    "RECORDERS",
    "recorder_states",
    "history_entropy",
]

BASES = "ACGT"
TRITS_PER_BYTE = 6  # 3^6 = 729 >= 256


def codec_source(n_bytes: int) -> str:
    """Reverie source for the rotating-code encoder over ``n_bytes`` bytes.

    Seeds: ``data`` (bytes) and ``dna[0]``, the primer base before the
    payload. Running it forward fills ``dna[1:]`` and zeroes ``data``;
    running it backward is the decoder."""
    n, t = n_bytes, n_bytes * TRITS_PER_BYTE
    digits = " + ".join(
        f"{3 ** k} * trits[{TRITS_PER_BYTE} * i + {k}]" for k in range(TRITS_PER_BYTE)
    )
    return f"""\
// Rotating-code DNA storage encoder (Goldman-style, no homopolymers).
// Generated by reverie.dna.codec_source. Forward: bytes -> bases.
// Backward: the decoder.

global data: tensor<int, {n}>;
global trits: tensor<int, {t}>;
global dna: tensor<int, {t + 1}>;
global prev: tensor<int, {t + 1}>;
global pow3: tensor<int, {TRITS_PER_BYTE}> = [{", ".join(str(3 ** k) for k in range(TRITS_PER_BYTE))}];

procedure main() {{
  iterate int i = 0 to {n - 1}
    iterate int k = 0 to {TRITS_PER_BYTE - 1}
      trits[{TRITS_PER_BYTE} * i + k] += data[i] / pow3[k] % 3
    end;
    data[i] -= {digits}
  end;
  // `prev` mirrors `dna` one step behind: the checker cannot prove that
  // dna[j + 1] and dna[j] are different cells, so each base is computed from
  // the mirror, which is uncomputed again at the end.
  prev[0] += dna[0];
  iterate int j = 0 to {t - 1}
    dna[j + 1] += (prev[j] + 1 + trits[j]) % 4;
    trits[j] -= (dna[j + 1] - prev[j] + 3) % 4;
    assert dna[j + 1] != prev[j];
    prev[j + 1] += dna[j + 1]
  end;
  iterate int j = 0 to {t}
    prev[j] -= dna[j]
  end
}}
"""


_CODECS: Dict[int, Program] = {}


def _codec(n: int) -> Program:
    if n not in _CODECS:
        _CODECS[n] = loads(codec_source(n))
    return _CODECS[n]


def encode(payload: bytes, primer: str = "A") -> str:
    """Bytes → DNA string (the primer base first)."""
    n = len(payload)
    store = {
        "data": list(payload),
        "dna": [BASES.index(primer)] + [0] * (n * TRITS_PER_BYTE),
    }
    out = _codec(n).run(store)
    assert all(v == 0 for name in ("data", "trits", "prev") for v in out[name])
    return "".join(BASES[b] for b in out["dna"])


def decode(strand: str) -> bytes:
    """DNA string (primer first) → bytes, by running the encoder backward."""
    t = len(strand) - 1
    if t % TRITS_PER_BYTE:
        raise ValueError("strand length does not hold whole bytes")
    n = t // TRITS_PER_BYTE
    store = {
        "data": [0] * n,
        "trits": [0] * t,
        "prev": [0] * (t + 1),
        "dna": [BASES.index(b) for b in strand],
    }
    back = _codec(n).reverse(store)
    if any(back["dna"][1:]):
        raise ValueError("strand did not decode cleanly")
    return bytes(back["data"])


# -- event recorders -------------------------------------------------------------


def tape_recorder_source(n_events: int, symbols: int) -> str:
    """A CRISPR-array / DNA-Typewriter-style recorder: each event writes its
    symbol into the next tape slot. The history is *moved* into DNA (the
    input tape ends empty), so no witness is needed and the backward run
    reads the history out of the DNA."""
    return f"""\
// Ordered tape recorder: event t writes symbol history[t] + 1 at slot t.
global history: tensor<int, {n_events}>;
global tape: tensor<int, {n_events}>;

procedure main() {{
  iterate int t = 0 to {n_events - 1}
    tape[t] += history[t] + 1;
    history[t] -= tape[t] - 1
  end
}}
"""


def flip_recorder_source(n_events: int, symbols: int) -> str:
    """An integrase-style recorder: event e flips site e if it is unflipped.
    The DNA records *which* events happened, not their order or repeats, so
    the history cannot be uncomputed: it stays as a witness. (Writing
    ``history[t] -= ...`` from the sites alone is rejected or traps.)"""
    return f"""\
// Site-flip recorder: each event flips its own site once.
global history: witness<tensor<int, {n_events}>>;
global site: tensor<int, {symbols}>;
global repeats: witness<tensor<int, {n_events}>>;

procedure main() {{
  iterate int t = 0 to {n_events - 1}
    if site[history[t]] == 0 then
      site[history[t]] += 1
    else
      repeats[t] += 1
    fi repeats[t] == 0
  end
}}
"""


def _tape(history: Sequence[int], symbols: int) -> Tuple:
    return tuple(history)


def _flip(history: Sequence[int], symbols: int) -> Tuple:
    return tuple(sorted(set(history)))


def _pairwise(history: Sequence[int], symbols: int) -> Tuple:
    """One domain per ordered pair of symbols that records which came first
    (the N^2-detector design): order of *first occurrences* survives,
    repeats and later order do not."""
    first: Dict[int, int] = {}
    for t, e in enumerate(history):
        first.setdefault(e, t)
    return tuple(
        sorted((a, b) for a in first for b in first if a != b and first[a] < first[b])
    ) + (tuple(sorted(first)),)


def _counter(history: Sequence[int], symbols: int) -> Tuple:
    """A counter per symbol (e.g. cumulative editing at one site per
    signal): counts survive, order does not."""
    counts = Counter(history)
    return tuple(counts.get(s, 0) for s in range(symbols))


def _capped_tape(history: Sequence[int], symbols: int, capacity: int = 3) -> Tuple:
    """A tape with a fixed number of slots: events after the tape is full
    are lost (the integrase "runs out of states" problem)."""
    return tuple(history[:capacity])


RECORDERS: Dict[str, Callable[[Sequence[int], int], Tuple]] = {
    "ordered tape (CRISPR array, DNA Typewriter)": _tape,
    "tape with 3 slots": _capped_tape,
    "pairwise first-order domains (N^2 detectors)": _pairwise,
    "per-signal counters": _counter,
    "site flips (integrase switches)": _flip,
}


def recorder_states(
    recorder: Callable[[Sequence[int], int], Tuple], n_events: int, symbols: int
) -> Dict[Tuple, int]:
    """Map every history of ``n_events`` events over ``symbols`` signals to
    the DNA state it leaves, and count histories per state."""
    states: Counter = Counter()
    for history in itertools.product(range(symbols), repeat=n_events):
        states[recorder(history, symbols)] += 1
    return dict(states)


def history_entropy(states: Dict[Tuple, int]) -> Tuple[float, float]:
    """(H(history), H(history | DNA)) in bits for uniformly random
    histories. The second number is exactly the witness the recorder would
    need for its history to be decoded, i.e. what it forgets."""
    total = sum(states.values())
    h = math.log2(total)
    h_given = sum(count * math.log2(count) for count in states.values()) / total
    return h, h_given
