"""Rollback netcode without snapshots: a reversible fighting-game step.

Rollback netcode (GGPO and its descendants) predicts the remote player's
input, and when the real input arrives late and differs, it restores the game
state from a few frames ago and re-simulates. Every implementation does that
by *snapshotting the whole game state every frame*.

:func:`fighting_game_source` writes the frame step as a Reverie program
instead. Rewinding is just running it backward, so there is no snapshot and
no serialization code. What a frame destroys (a wall clamp, a bounce, a
health floor, a cooldown tick) is recorded as a small witness, and almost
all of it is zero on most frames.

The game: two fighters on a line, with position, velocity, health and attack
cooldown, plus ``n_projectiles`` particles bouncing in a box (scenery that
scales the state, like projectiles or debris in a real game). Inputs per
frame and player: ``move`` in {-1, 0, 1} and ``attack`` in {0, 1}. All
arithmetic is integer, so the simulation is identical on every platform,
which rollback netcode requires.

:class:`Rollback` drives a match with delayed remote input and compares two
rollback strategies, snapshot-restore and reverse execution, against a ground
truth simulated with every input known in advance.
"""

from __future__ import annotations

import copy
import random
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional, Sequence

from ._reverie import Program, loads

__all__ = [
    "fighting_game_source",
    "STATE",
    "WITNESS",
    "Match",
    "Rollback",
    "random_inputs",
]

ARENA = 10_000
BOX = 4_000
ACCEL = 30
VMAX = 120
RANGE = 900
DAMAGE = 7
COOLDOWN = 24
START_HP = 100

#: Game-state variables (what a snapshot must store).
STATE = ("px", "pv", "hp", "cd", "qx", "qy", "qvx", "qvy")
#: Witness tapes (what reverse execution must store), per frame.
WITNESS = ("vclip", "wclip", "cdtick", "hit", "hpclip", "bounce_x", "bounce_y")


def _fighter(p: int) -> str:
    return f"""\
    pv[{p}] += move[f][{p}] * {ACCEL};
    if pv[{p}] > {VMAX} then
      vclip[f][{p}] += pv[{p}] - {VMAX};
      pv[{p}] -= vclip[f][{p}]
    fi vclip[f][{p}] > 0;
    if pv[{p}] < 0 - {VMAX} then
      vclip[f][{p}] += pv[{p}] + {VMAX};
      pv[{p}] -= vclip[f][{p}]
    fi vclip[f][{p}] < 0;
    px[{p}] += pv[{p}];
    if px[{p}] > {ARENA} then
      wclip[f][{p}] += px[{p}] - {ARENA};
      px[{p}] -= wclip[f][{p}]
    fi wclip[f][{p}] > 0;
    if px[{p}] < 0 then
      wclip[f][{p}] += px[{p}];
      px[{p}] -= wclip[f][{p}]
    fi wclip[f][{p}] < 0;
    if cd[{p}] > 0 then
      cd[{p}] -= 1;
      cdtick[f][{p}] += 1
    fi cdtick[f][{p}] == 1"""


def _attack(p: int) -> str:
    o = 1 - p
    return f"""\
    if attack[f][{p}] == 1 && cd[{p}] == 0 && px[{p}] - px[{o}] < {RANGE} && px[{o}] - px[{p}] < {RANGE} then
      hit[f][{p}] += 1;
      cd[{p}] += {COOLDOWN};
      hp[{o}] -= {DAMAGE};
      if hp[{o}] < 0 then
        hpclip[f][{o}] += hp[{o}];
        hp[{o}] -= hpclip[f][{o}]
      fi hpclip[f][{o}] < 0
    fi hit[f][{p}] == 1"""


def fighting_game_source(*, n_projectiles: int, frames: int) -> str:
    """Reverie source for ``frames`` frames of the game. Seeds: the state
    (``STATE``), the input tapes ``move``/``attack`` (``frames x 2``), and the
    inclusive frame range ``start``/``stop``."""
    n, t = max(n_projectiles, 1), frames
    projectile = f"""\
    iterate int i = 0 to {n_projectiles - 1}
      qx[i] += qvx[i];
      if qx[i] > {BOX} then
        bounce_x[f][i] += 1;
        qx[i] *= -1;
        qx[i] += {2 * BOX};
        qvx[i] *= -1
      fi bounce_x[f][i] == 1;
      if qx[i] < 0 then
        bounce_x[f][i] += 2;
        qx[i] *= -1;
        qvx[i] *= -1
      fi bounce_x[f][i] == 2;
      qy[i] += qvy[i];
      if qy[i] > {BOX} then
        bounce_y[f][i] += 1;
        qy[i] *= -1;
        qy[i] += {2 * BOX};
        qvy[i] *= -1
      fi bounce_y[f][i] == 1;
      if qy[i] < 0 then
        bounce_y[f][i] += 2;
        qy[i] *= -1;
        qvy[i] *= -1
      fi bounce_y[f][i] == 2
    end""" if n_projectiles > 0 else "    skip"
    return f"""\
// A two-player fighting game with {n_projectiles} bouncing projectiles,
// written reversibly so rollback netcode can rewind by running backward.
// Generated by reverie.rollback.fighting_game_source.

global move: tensor<int, {t}, 2>;
global attack: tensor<int, {t}, 2>;
global start = 0;
global stop = 0;

global px: tensor<int, 2>;
global pv: tensor<int, 2>;
global hp: tensor<int, 2>;
global cd: tensor<int, 2>;
global qx: tensor<int, {n}>;
global qy: tensor<int, {n}>;
global qvx: tensor<int, {n}>;
global qvy: tensor<int, {n}>;

global vclip: witness<tensor<int, {t}, 2>>;
global wclip: witness<tensor<int, {t}, 2>>;
global cdtick: witness<tensor<int, {t}, 2>>;
global hit: witness<tensor<int, {t}, 2>>;
global hpclip: witness<tensor<int, {t}, 2>>;
global bounce_x: witness<tensor<int, {t}, {n}>>;
global bounce_y: witness<tensor<int, {t}, {n}>>;

procedure main() {{
  iterate int f = start to stop
{_fighter(0)};
{_fighter(1)};
{_attack(0)};
{_attack(1)};
{projectile}
  end
}}
"""


def random_inputs(frames: int, rng: random.Random, *, stickiness: float = 0.85):
    """Human-ish inputs: each player holds a direction for a while and
    occasionally attacks."""
    move = [[0, 0] for _ in range(frames)]
    attack = [[0, 0] for _ in range(frames)]
    held = [0, 0]
    for f in range(frames):
        for p in range(2):
            if rng.random() > stickiness:
                held[p] = rng.choice((-1, 0, 1))
            move[f][p] = held[p]
            attack[f][p] = 1 if rng.random() < 0.08 else 0
    return move, attack


def initial_state(n_projectiles: int, rng: random.Random) -> Dict[str, Any]:
    n = max(n_projectiles, 1)
    return {
        "px": [ARENA // 2 - 600, ARENA // 2 + 600],
        "pv": [0, 0],
        "hp": [START_HP, START_HP],
        "cd": [0, 0],
        "qx": [rng.randrange(BOX) for _ in range(n)],
        "qy": [rng.randrange(BOX) for _ in range(n)],
        "qvx": [rng.randrange(-90, 91) for _ in range(n)],
        "qvy": [rng.randrange(-90, 91) for _ in range(n)],
    }


@dataclass
class Match:
    """A full match: the program, the initial state and the true inputs."""

    n_projectiles: int
    frames: int
    seed: int = 0
    engine: str = "slot"
    program: Program = field(init=False)
    state0: Dict[str, Any] = field(init=False)
    move: List[List[int]] = field(init=False)
    attack: List[List[int]] = field(init=False)

    def __post_init__(self) -> None:
        rng = random.Random(self.seed)
        self.program = loads(
            fighting_game_source(n_projectiles=self.n_projectiles, frames=self.frames),
            engine=self.engine,
        )
        self.state0 = initial_state(self.n_projectiles, rng)
        self.move, self.attack = random_inputs(self.frames, rng)

    def store(self, state, move, attack, start, stop, witness=None) -> Dict[str, Any]:
        store = dict(state)
        store.update(move=move, attack=attack, start=start, stop=stop)
        if witness is not None:
            store.update(witness)
        return store

    def ground_truth(self) -> Dict[str, Any]:
        """Every frame simulated with the true inputs known in advance."""
        return self.program.run(
            self.store(self.state0, self.move, self.attack, 0, self.frames - 1)
        )


@dataclass
class RollbackStats:
    rollbacks: int = 0
    frames_resimulated: int = 0
    frames_reversed: int = 0
    frames_simulated: int = 0
    max_depth: int = 0


class Rollback:
    """Play a match where player 1's inputs arrive ``delay`` frames late,
    predicting "same as last confirmed input" and rolling back on a
    misprediction, either from snapshots (``mode="snapshot"``) or by running
    the frame step backward (``mode="reverse"``)."""

    def __init__(self, match: Match, *, delay: int, mode: str) -> None:
        if mode not in ("snapshot", "reverse"):
            raise ValueError(mode)
        self.match, self.delay, self.mode = match, delay, mode
        self.stats = RollbackStats()

    def play(self) -> Dict[str, Any]:
        m = self.match
        t = m.frames
        move = [[m.move[f][0], 0] for f in range(t)]
        attack = [[m.attack[f][0], 0] for f in range(t)]
        confirmed = -1  # last frame whose remote input is known
        state = copy.deepcopy(m.state0)
        witness: Optional[Dict[str, Any]] = None
        snapshots: Dict[int, Dict[str, Any]] = {}

        def predict_from(frame: int) -> None:
            last = (m.move[confirmed][1], m.attack[confirmed][1]) if confirmed >= 0 else (0, 0)
            for g in range(frame, t):
                move[g][1], attack[g][1] = last

        predict_from(0)
        # Run `delay` extra ticks after the last frame so the final remote
        # inputs arrive and any last mispredictions are corrected.
        for tick in range(t + self.delay):
            now = min(tick, t)  # frames simulated so far
            arrived = tick - self.delay
            if arrived >= 0:
                truth = (m.move[arrived][1], m.attack[arrived][1])
                guessed = (move[arrived][1], attack[arrived][1])
                confirmed = arrived
                if truth != guessed and arrived < now:
                    # Roll back to the start of frame `arrived`, fix the
                    # inputs, and re-simulate up to `now`.
                    depth = now - arrived
                    if self.mode == "snapshot":
                        state = copy.deepcopy(snapshots[arrived])
                    else:
                        full = m.store(state, move, attack, arrived, now - 1, witness)
                        back = m.program.reverse(full)
                        state = {k: back[k] for k in STATE}
                        witness = {k: back[k] for k in WITNESS}
                        self.stats.frames_reversed += depth
                    predict_from(arrived)
                    move[arrived][1], attack[arrived][1] = truth
                    out = m.program.run(m.store(state, move, attack, arrived, now - 1, witness))
                    state = {k: out[k] for k in STATE}
                    witness = self._keep_witness(out)
                    if self.mode == "snapshot":
                        for g in range(arrived + 1, now):
                            snapshots[g] = None  # stale; refreshed below
                        self._resnapshot(arrived, now, move, attack, snapshots)
                    self.stats.rollbacks += 1
                    self.stats.frames_resimulated += depth
                    self.stats.max_depth = max(self.stats.max_depth, depth)
                else:
                    move[arrived][1], attack[arrived][1] = truth
            if tick >= t:
                continue
            if self.mode == "snapshot":
                snapshots[now] = copy.deepcopy(state)
                # Snapshots older than the delay can never be needed again.
                snapshots.pop(now - self.delay - 1, None)
            out = m.program.run(m.store(state, move, attack, now, now, witness))
            state = {k: out[k] for k in STATE}
            witness = self._keep_witness(out)
            self.stats.frames_simulated += 1
        final = dict(state)
        final.update(witness or {})
        return final

    def _keep_witness(self, out: Dict[str, Any]) -> Optional[Dict[str, Any]]:
        # A snapshot engine never runs backward, so it discards the witness
        # (every run starts from empty tapes); the reverse engine keeps it.
        if self.mode == "snapshot":
            return None
        return {k: out[k] for k in WITNESS}

    def _resnapshot(self, start, stop, move, attack, snapshots) -> None:
        """After re-simulating from a snapshot, the snapshots for the
        re-simulated frames are stale. Rebuild them frame by frame (a real
        engine saves them during re-simulation)."""
        m = self.match
        state = copy.deepcopy(snapshots[start])
        for g in range(start, stop):
            snapshots[g] = copy.deepcopy(state)
            out = m.program.run(m.store(state, move, attack, g, g))
            state = {k: out[k] for k in STATE}
