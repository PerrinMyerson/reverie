"""Data migrations whose down-migration is generated and exact.

Schema tools can generate a down-migration for the schema, but not for data
transformations: Prisma's docs say data changed during an up-migration is not
changed back. Here the data transformation is a Reverie program, so the
down-migration is the same program run backward. Wherever the up-migration
destroys information (a currency conversion that rounds, a status code
collapsed from 6 values to 3, a dropped column), Reverie's checker refuses
the program unless that information is kept as a witness, so "this rollback
will lose data" is a compile-time error rather than a production surprise.

The example table (v1 → v2):

* ``price`` in the row's ``currency`` (USD, EUR, GBP) → ``usd`` cents, at
  fixed rates; witness: the rounding remainder and the original currency;
* ``status`` 0–5 → ``status3`` 0–2; witness: the dropped low bit;
* ``flag_a``, ``flag_b``, ``flag_c`` → one packed ``flags`` column (lossless,
  no witness);
* ``legacy_score`` dropped; witness: the archived column.
"""

from __future__ import annotations

import random
from typing import Any, Dict, List

from ._reverie import Program, loads

__all__ = [
    "RATES",
    "V1",
    "V2",
    "WITNESS",
    "migration_source",
    "random_rows",
    "LOSSY_DROP_SOURCE",
]

#: Fixed conversion rates to USD, per 10,000 units.
RATES = {0: 10_000, 1: 10_832, 2: 12_689}
V1 = ("price", "currency", "status", "flag_a", "flag_b", "flag_c", "legacy_score")
V2 = ("usd", "status3", "flags")
WITNESS = ("rem", "orig_currency", "status_bit", "archived_score")


def migration_source(rows: int) -> str:
    """Reverie source for the v1 → v2 migration over ``rows`` rows."""
    conversions = []
    for code, rate in RATES.items():
        if rate == 10_000:
            body = """\
      usd[r] += price[r];
      price[r] -= usd[r]"""
        else:
            body = f"""\
      usd[r] += price[r] * {rate} / 10000;
      rem[r] += price[r] * {rate} % 10000;
      price[r] -= (usd[r] * 10000 + rem[r]) / {rate}"""
        conversions.append(
            f"""\
    if currency[r] == {code} then
{body}
    fi currency[r] == {code}"""
        )
    columns = "\n".join(
        f"global {name}: tensor<int, {rows}>;" for name in V1 + V2
    )
    conversion_block = ";\n".join(conversions)
    witnesses = "\n".join(
        f"global {name}: witness<tensor<int, {rows}>>;" for name in WITNESS
    )
    return f"""\
// v1 -> v2 data migration over {rows} rows. Generated by
// reverie.migrate.migration_source. Run forward to migrate up; run backward
// for the exact down-migration.

{columns}
{witnesses}

procedure main() {{
  iterate int r = 0 to {rows - 1}
{conversion_block};
    orig_currency[r] += currency[r];
    currency[r] -= orig_currency[r];
    status3[r] += status[r] / 2;
    status_bit[r] += status[r] % 2;
    status[r] -= status3[r] * 2 + status_bit[r];
    flags[r] += flag_a[r] + 2 * flag_b[r] + 4 * flag_c[r];
    flag_a[r] -= flags[r] & 1;
    flag_b[r] -= (flags[r] / 2) & 1;
    flag_c[r] -= (flags[r] / 4) & 1;
    archived_score[r] += legacy_score[r];
    legacy_score[r] -= archived_score[r]
  end
}}
"""


#: Dropping a column without archiving it. Reverie rejects it.
LOSSY_DROP_SOURCE = """\
global legacy_score: tensor<int, 4>;

procedure main() {
  iterate int r = 0 to 3
    legacy_score[r] -= legacy_score[r]
  end
}
"""


def random_rows(rows: int, rng: random.Random) -> Dict[str, List[int]]:
    table = {name: [] for name in V1}
    for _ in range(rows):
        table["price"].append(rng.randrange(0, 500_000))
        table["currency"].append(rng.choice((0, 0, 1, 2)))
        table["status"].append(rng.randrange(6))
        for flag in ("flag_a", "flag_b", "flag_c"):
            table[flag].append(rng.randrange(2))
        table["legacy_score"].append(rng.randrange(-1000, 100_000))
    return table


def schema_only_down(rows: int) -> Dict[str, List[int]]:
    """What a schema-diff down-migration gives back: the old columns, empty."""
    return {name: [0] * rows for name in V1}


def hand_written_down(v2: Dict[str, List[int]]) -> Dict[str, List[int]]:
    """A plausible hand-written data down-migration without the witness: it
    has to guess the currency (assume USD), the status low bit (assume 0)
    and the dropped column (gone)."""
    rows = len(v2["usd"])
    return {
        "price": list(v2["usd"]),
        "currency": [0] * rows,
        "status": [s * 2 for s in v2["status3"]],
        "flag_a": [f & 1 for f in v2["flags"]],
        "flag_b": [(f >> 1) & 1 for f in v2["flags"]],
        "flag_c": [(f >> 2) & 1 for f in v2["flags"]],
        "legacy_score": [0] * rows,
    }
